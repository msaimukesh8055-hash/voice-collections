// scripts/seed/render-sql.ts
// Turns the generated book into supabase/seed.sql. Dates are written relative to the India date
// on the day the seed is applied, so a re-seed on demo day gives a fresh story.
import { OWNER } from './names.ts';
import type {
  PromiseDay,
  SeedData,
  SeedEntry,
  SeedPromise,
  SeedShopkeeper,
} from './generate-seed.ts';

const TODAY_CTE = "with d as (select (now() at time zone 'Asia/Kolkata')::date as today)";
/** Most recent Friday strictly before today (ISO weekday: Monday 1 … Sunday 7). */
const LAST_FRIDAY = 'd.today - ((extract(isodow from d.today)::int + 1) % 7 + 1)';
const PROMISE_TIME = "time '11:00'";

function text(value: string | null): string {
  return value === null ? 'null::text' : `'${value.replaceAll("'", "''")}'`;
}

export function dayExpression(day: number): string {
  if (day === 0) return 'd.today';
  return day < 0 ? `d.today - ${-day}` : `d.today + ${day}`;
}

function promiseDayExpression(day: PromiseDay): string {
  return day === 'last_friday' ? `(${LAST_FRIDAY})` : dayExpression(day);
}

const HEADER = `-- supabase/seed.sql
-- GENERATED by scripts/seed/write-seed.ts (npm run seed:generate). Do not edit by hand.
-- FAKE DATA ONLY: invented names, shops and amounts. Phone numbers use +91 00000 xxxxx, a range
-- no real phone can have. The owner's real WhatsApp number comes from .env in M4, never from here.
-- Re-applying this seed wipes the demo data (calls, tool events, promises) and starts fresh.

truncate table public.owners restart identity cascade;
`;

function ownerSql(): string {
  // english_under_telugu: the M6 demo setting, on for the demo owner (Saim).
  return `insert into public.owners (id, name, business_name, city, language, english_under_telugu) values
  (${text(OWNER.id)}, ${text(OWNER.name)}, ${text(OWNER.businessName)}, ${text(OWNER.city)}, ${text(OWNER.language)}, true);
`;
}

function shopkeeperRow(s: SeedShopkeeper): string {
  const values = [s.id, OWNER.id, s.name, s.shopName, s.area, s.phone, s.language, s.persona];
  return `  (${values.map(text).join(', ')})`;
}

function shopkeepersSql(shopkeepers: readonly SeedShopkeeper[]): string {
  return `insert into public.shopkeepers (id, owner_id, name, shop_name, area, phone, language, persona) values
${shopkeepers.map(shopkeeperRow).join(',\n')};
`;
}

function entryRow(entry: SeedEntry): string {
  const due = entry.dueDay === null ? 'null::date' : dayExpression(entry.dueDay);
  return `  (${text(entry.kind)}, ${entry.amount}, ${dayExpression(entry.day)}, ${due}, ${text(entry.status)}, ${text(entry.mode)})`;
}

function ledgerSql(shopkeeper: SeedShopkeeper, entries: readonly SeedEntry[]): string {
  return `-- ${shopkeeper.shopName} (${shopkeeper.profile})
${TODAY_CTE}
insert into public.ledger_entries (shopkeeper_id, kind, amount, entry_date, due_date, status, source, payment_mode)
select ${text(shopkeeper.id)}::uuid, v.kind, v.amount, v.entry_date, v.due_date, v.status, 'seed', v.payment_mode
from d cross join lateral (values
${entries.map(entryRow).join(',\n')}
) as v(kind, amount, entry_date, due_date, status, payment_mode);
`;
}

function promiseRow(promise: SeedPromise): string {
  const created = `(${dayExpression(promise.createdDay)} + ${PROMISE_TIME}) at time zone 'Asia/Kolkata'`;
  return `  (${text(promise.shopkeeperId)}::uuid, ${promise.amount}, ${promiseDayExpression(promise.day)}, ${text(promise.status)}, ${created})`;
}

function promisesSql(promises: readonly SeedPromise[]): string {
  return `${TODAY_CTE}
insert into public.promises (shopkeeper_id, amount, promise_date, status, created_at)
select v.shopkeeper_id, v.amount, v.promise_date, v.status, v.created_at
from d cross join lateral (values
${promises.map(promiseRow).join(',\n')}
) as v(shopkeeper_id, amount, promise_date, status, created_at);
`;
}

function demoSettingsSql(liveShopkeeperId: string): string {
  return `insert into public.demo_settings (id, live_shopkeeper_id) values (1, ${text(liveShopkeeperId)});
`;
}

export function renderSeedSql(data: SeedData): string {
  const ledgers = data.shopkeepers.map((shopkeeper) =>
    ledgerSql(
      shopkeeper,
      data.entries.filter((entry) => entry.shopkeeperId === shopkeeper.id),
    ),
  );
  const live = data.shopkeepers[0]?.id;
  if (live === undefined) throw new Error('The seed needs at least one shopkeeper');
  return [
    HEADER,
    ownerSql(),
    shopkeepersSql(data.shopkeepers),
    ...ledgers,
    promisesSql(data.promises),
    demoSettingsSql(live),
  ].join('\n');
}
