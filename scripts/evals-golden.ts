// scripts/evals-golden.ts
// npm run evals:golden — writes the golden outcomes (evals/golden.ts, built from the case
// definitions in evals/) into supabase/functions/_shared/evals/golden-cases.ts, where the
// deployed calls-api can read them for the Evals page. Run it after changing any eval case;
// evals/golden.test.ts fails until you do. Free: reads code only, calls nothing.
import { writeFileSync } from 'node:fs';
import { buildGolden } from '../evals/golden.ts';

const OUT_PATH = 'supabase/functions/_shared/evals/golden-cases.ts';

// deno fmt would turn the 2,000-odd lines of JSON into a different shape on every regeneration,
// and max-lines is for hand-written code: the generated file opts out of both.
const HEADER = [
  `// ${OUT_PATH}`,
  '// deno-fmt-ignore-file',
  '/* eslint-disable max-lines */',
  '// GENERATED by `npm run evals:golden` from the eval case definitions in evals/ (golden.ts).',
  '// Do not edit by hand: change the case, then run the script. evals/golden.test.ts fails when',
  '// this file and the cases disagree.',
  "import type { Golden } from './golden.ts';",
  '',
].join('\n');

const body = `export const GOLDEN: Golden = ${JSON.stringify(buildGolden(), null, 2)};\n`;
writeFileSync(OUT_PATH, `${HEADER}\n${body}`, 'utf8');
process.stdout.write(`wrote ${OUT_PATH}\n`);
